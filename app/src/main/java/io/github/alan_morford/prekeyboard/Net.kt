package io.github.alan_morford.prekeyboard

import android.os.Build
import java.io.ByteArrayInputStream
import java.net.HttpURLConnection
import java.net.URL
import java.security.KeyStore
import java.security.cert.CertificateFactory
import java.security.cert.X509Certificate
import javax.net.ssl.HttpsURLConnection
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLSocketFactory
import javax.net.ssl.TrustManagerFactory

/**
 * Connections for updates. GitHub hands release downloads to a host whose certificate comes
 * from Let's Encrypt, under ISRG Root X1, which Android only trusts from 7.1.1 (API 25). Before
 * that (a Nexus 7 on Android 6, say) the download failed with "Trust anchor for certification
 * path not found". So there, these connections trust ISRG's two roots as well as the system's
 * own; from 7.1.1 on they are plain connections.
 */
object Net {

    /** Opens [url], following redirects itself so every hop gets the same trust. */
    fun open(url: String, configure: (HttpURLConnection) -> Unit): HttpURLConnection {
        var current = URL(url)
        repeat(6) {
            val conn = current.openConnection() as HttpURLConnection
            factory?.let { f -> (conn as? HttpsURLConnection)?.sslSocketFactory = f }
            conn.instanceFollowRedirects = false
            configure(conn)
            val code = conn.responseCode
            if (code !in 300..399 || code == 304) return conn
            val next = conn.getHeaderField("Location")
            conn.disconnect()
            if (next == null) throw RuntimeException("HTTP $code without a destination")
            current = URL(current, next)
            if (current.protocol != "https") throw RuntimeException("redirected off https")
        }
        throw RuntimeException("too many redirects")
    }

    private val factory: SSLSocketFactory? by lazy {
        if (Build.VERSION.SDK_INT >= 25) return@lazy null
        val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
        // The system's own roots first, so nothing that worked before stops working.
        val system = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
        system.init(null as KeyStore?)
        var n = 0
        for (tm in system.trustManagers)
            if (tm is javax.net.ssl.X509TrustManager)
                for (cert in tm.acceptedIssuers) store.setCertificateEntry("system${n++}", cert)
        val cf = CertificateFactory.getInstance("X.509")
        for ((name, pem) in ROOTS)
            store.setCertificateEntry(name, cf.generateCertificate(ByteArrayInputStream(pem.toByteArray())) as X509Certificate)
        val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
        tmf.init(store)
        SSLContext.getInstance("TLS").apply { init(null, tmf.trustManagers, null) }.socketFactory
    }

