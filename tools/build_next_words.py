#!/usr/bin/env python3
"""Build app/src/main/assets/next_words.txt, the words the bar offers before a word is typed.

What follows what comes from Tatoeba's English sentences (https://tatoeba.org), which are
CC BY 2.0 FR - so the generated file is too; see NOTICE. Tatoeba is everyday, spoken-style
English, close to what people type in messages.

    curl -LO https://downloads.tatoeba.org/exports/per_language/eng/eng_sentences.tsv.bz2
    python3 tools/build_next_words.py eng_sentences.tsv.bz2 app/src/main/assets/dictionary.txt app/src/main/assets/next_words.txt

Other languages name theirs after the dictionary and, last, the English dictionary, whose
capitalised words are the names to leave out (in German every noun is capitalised, so the
English way of telling names doesn't work there):

    python3 tools/build_next_words.py deu_sentences.tsv.bz2 app/src/main/assets/de/dictionary.txt \
        app/src/main/assets/de/next_words.txt de app/src/main/assets/dictionary.txt

In French and Italian an elided word ("l'homme", "dell'anno") counts as the word after its
apostrophe, as the keyboard reads it.

Output, one line per word that comes before:  word<TAB>next1 next2 next3 next4 next5
likeliest first. "<s>" is the start of a sentence (or of the text), "<,>" straight after a
comma. Only dictionary words come out, in the dictionary's case ("I", "I'm"), and no names
(a word these sentences mostly capitalise mid-sentence): Tatoeba is full of Tom and Mary,
who would otherwise start every sentence.
"""
import bz2, collections, re, sys

src, dict_path, out = sys.argv[1:4]
lang = sys.argv[4] if len(sys.argv) > 4 else "en"
KEEP = 5
MIN_PAIR = 3          # a pair seen fewer times is noise
MIN_WORD = 30         # a word seen fewer times before something gets no line of its own

case = {}
for line in open(dict_path, encoding="utf-8"):
    if line.startswith("#") or "\t" not in line:
        continue
    w = line.split("\t")[0]
    k = w.lower()
    if k not in case or w == k:
        case[k] = w

english_names = set()
if lang != "en":
    for line in open(sys.argv[5], encoding="utf-8"):
        w = line.split("\t")[0]
        if not line.startswith("#") and w[:1].isupper() and w != "I" and not w.startswith("I'"):
            english_names.add(w.lower())

def usable(k):
    w = case.get(k)
    if w is None:
        return False
    if lang == "de":
        return k not in english_names
    # A capitalised dictionary word is a name, except I and its contractions.
    return w[0].islower() or k == "i" or k.startswith("i'")

if lang == "en":
    TOKEN = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*|[.!?]+|,|[;:]|[^\sA-Za-z]")
else:
    # Any letters; an elided word ("l'", "dell'") is dropped from the front of the next.
    TOKEN = re.compile(r"(?:[^\W\d_]+['’])?[^\W\d_]+|[.!?]+|,|[;:]|[^\w\s]|\d+")
pairs = collections.defaultdict(collections.Counter)
# How often each word is capitalised away from a sentence's start: "tom" is a word, but in
# these sentences it is nearly always Tom.
upper, lower = collections.Counter(), collections.Counter()
opener = open if not src.endswith(".bz2") else bz2.open
with opener(src, "rt", encoding="utf-8") as f:
    lines = [l for l in f]
for line in lines:
    parts = line.rstrip("\n").split("\t")
    if len(parts) < 3:
        continue
    toks = TOKEN.findall(parts[2])
    for a, t in zip(toks, toks[1:]):
        if t[0].isalpha() and a[0] not in ".!?\"'“":
            (upper if t[0].isupper() else lower)[t.lower()] += 1
names = {k for k in upper if k != "i" and not k.startswith("i'") and upper[k] > lower[k]}
if lang != "en":
    names = english_names

if True:
    for line in lines:
        parts = line.rstrip("\n").split("\t")
        if len(parts) < 3:
            continue
        prev = "<s>"
        for t in TOKEN.findall(parts[2]):
            t = t.replace("’", "'")
            if lang != "en" and "'" in t and len(t) > 1:
                t = t.split("'")[-1]
            if t[0] in ".!?":
                prev = "<s>"
            elif t == ",":
                prev = "<,>"
            elif t[0].isalpha():
                k = t.lower()
                if prev is not None and usable(k) and k not in names:
                    pairs[prev][k] += 1
                prev = k if k in case else None
            else:
                prev = None          # quotes, dashes, digits: no clean context

rows = []
for prev, c in pairs.items():
    if sum(c.values()) < MIN_WORD:
        continue
    best = [w for w, n in c.most_common() if n >= MIN_PAIR and w != prev][:KEEP]
    if best:
        rows.append((prev, best))
rows.sort()
with open(out, "w", encoding="utf-8") as f:
    which = "English" if lang == "en" else lang
    f.write(f"# Generated by tools/build_next_words.py from Tatoeba's {which} sentences. CC BY 2.0 FR.\n")
    for prev, best in rows:
        f.write(prev + "\t" + " ".join(case[w] for w in best) + "\n")
print(f"{len(rows)} words -> {out}")
