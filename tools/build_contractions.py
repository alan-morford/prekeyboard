#!/usr/bin/env python3
"""Build app/src/main/assets/contractions.txt: which of an everyday word and the contraction
it also spells without its apostrophe ("ill" and "I'll", "its" and "it's") comes after what.

Counted from Tatoeba's English sentences (https://tatoeba.org), CC BY 2.0 FR - so the
generated file is too; see NOTICE. The same sentences, and the same contexts, as
tools/build_next_words.py:

    curl -LO https://downloads.tatoeba.org/exports/per_language/eng/eng_sentences.tsv.bz2
    python3 tools/build_contractions.py eng_sentences.tsv.bz2 app/src/main/assets/contractions.txt

Output, one line per word and context seen at least MIN times:
    word<TAB>context<TAB>times as the word<TAB>times as the contraction
"<s>" is the start of a sentence, "<,>" straight after a comma. The keyboard keeps these in
step with Corrector.AMBIGUOUS.
"""
import bz2, collections, re, sys

src, out = sys.argv[1:3]
PAIRS = {"ill": "i'll", "its": "it's", "well": "we'll", "were": "we're", "lets": "let's",
         "wed": "we'd", "hell": "he'll", "shell": "she'll", "shed": "she'd"}
BARE = {c: b for b, c in PAIRS.items()}
MIN = 3

TOKEN = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)*|[.!?]+|,|[;:]|[^\sA-Za-z]")
counts = collections.defaultdict(lambda: [0, 0])     # (word, context) -> [bare, contraction]
opener = open if not src.endswith(".bz2") else bz2.open
with opener(src, "rt", encoding="utf-8") as f:
    for line in f:
        parts = line.rstrip("\n").split("\t")
        if len(parts) < 3:
            continue
        prev = "<s>"
        for t in TOKEN.findall(parts[2]):
            t = t.replace("’", "'")
            if t[0] in ".!?":
                prev = "<s>"
            elif t == ",":
                prev = "<,>"
            elif t[0].isalpha():
                k = t.lower()
                if prev is not None:
                    if k in PAIRS:
                        counts[(k, prev)][0] += 1
                    elif k in BARE:
                        counts[(BARE[k], prev)][1] += 1
                prev = k
            else:
                prev = None          # quotes, dashes, digits: no clean context

rows = sorted((w, ctx, n[0], n[1]) for (w, ctx), n in counts.items() if n[0] + n[1] >= MIN)
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by tools/build_contractions.py from Tatoeba's English sentences. CC BY 2.0 FR.\n")
    for w, ctx, a, b in rows:
        f.write(f"{w}\t{ctx}\t{a}\t{b}\n")
print(f"{len(rows)} lines -> {out}")
