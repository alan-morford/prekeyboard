#!/usr/bin/env python3
"""Build app/src/main/assets/zh/pinyin.txt: Simplified Chinese words by their pinyin, for typing
Chinese as pinyin.

The words and their readings come from CC-CEDICT (https://www.mdbg.net/chinese/dictionary?page=cedict,
CC BY-SA 4.0); how common each is, from Hermit Dave's FrequencyWords zh_cn (OpenSubtitles 2018,
CC BY-SA 4.0), which lists segmented words. A common word from the subtitles that CC-CEDICT
lacks is added when every character in it has only one reading. The generated file is
CC BY-SA 4.0.

    curl -LO https://www.mdbg.net/chinese/export/cedict/cedict_1_0_ts_utf-8_mdbg.txt.gz
    curl -LO https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/zh_cn/zh_cn_full.txt
    python3 tools/build_pinyin.py cedict_1_0_ts_utf-8_mdbg.txt.gz zh_cn_full.txt app/src/main/assets/zh/pinyin.txt

Each line is
    pinyin<TAB>word<TAB>score
the pinyin in plain letters without tones or spaces ("nihao"; ü as v: "lv"), score log2 of
the word's subtitle count (0-22), most common first within each pinyin, sorted by pinyin.
"""
import collections, gzip, math, re, sys

cedict, freq_path, out = sys.argv[1:4]

HAN = re.compile(r"^[㐀-鿿]+$")
SYLLABLE = re.compile(r"^[a-z]+[1-5]$")
# A word from the subtitles needs this many sightings; CC-CEDICT's own words need fewer.
MIN_EXTRA = 50
MIN_CEDICT = 3

counts = {}
with open(freq_path, encoding="utf-8") as f:
    for line in f:
        parts = line.split()
        if len(parts) == 2 and HAN.match(parts[0]):
            counts[parts[0]] = int(parts[1])

# Each character's count, over every word it is in: how common a character is on its own
# terms, for characters the subtitles rarely list alone.
char_counts = collections.Counter()
for w, n in counts.items():
    for ch in w:
        char_counts[ch] += n

entries = {}                      # (key, word) -> score
readings = collections.defaultdict(set)
# How often each reading of a character is the one used, over the words it is in: a character
# with several readings (见 jian, rarely xian) shares its count between them so.
usage = collections.defaultdict(collections.Counter)
singles = []                      # (character, reading): scored once usage is known

def parse(line):
    m = re.match(r"^(\S+) (\S+) \[([^\]]+)\] /(.*)/$", line.strip())
    if not m:
        return None
    simp, pin, gloss = m.group(2), m.group(3), m.group(4)
    if not HAN.match(simp):
        return None
    sylls = pin.lower().replace("u:", "v").split()
    if len(sylls) != len(simp) or not all(SYLLABLE.match(s) for s in sylls):
        return None
    return simp, [s[:-1] for s in sylls], gloss

with gzip.open(cedict, "rt", encoding="utf-8") as f:
    for line in f:
        if line.startswith("#"):
            continue
        p = parse(line)
        if p and len(p[0]) > 1:
            n = counts.get(p[0], 0)
            for ch, r in zip(p[0], p[1]):
                usage[ch][r] += n

with gzip.open(cedict, "rt", encoding="utf-8") as f:
    for line in f:
        if line.startswith("#"):
            continue
        p = parse(line)
        if not p:
            continue
        simp, plain, gloss = p
        # Surnames and old variants only: CC-CEDICT gives these readings their own entries.
        if gloss.startswith("surname ") and "/" not in gloss or gloss.startswith("variant of") or gloss.startswith("old variant of"):
            if len(simp) > 1:
                continue
        key = "".join(plain)
        if len(simp) == 1:
            readings[simp].add(plain[0])
            singles.append((simp, plain[0]))
            continue
        n = counts.get(simp, 0)
        if n < MIN_CEDICT:
            continue
        score = int(math.log2(n)) if n > 0 else 0
        k = (key, simp)
        entries[k] = max(entries.get(k, -1), score)

for ch, r in set(singles):
    n = max(counts.get(ch, 0), char_counts.get(ch, 0) // 4)
    u = usage[ch]
    rs = readings[ch]
    share = (u[r] + 1) / (sum(u[x] for x in rs) + len(rs))
    n = n * share
    entries[(r, ch)] = int(math.log2(n)) if n >= 1 else 0

# Common words CC-CEDICT lacks, read character by character where that is certain.
added = 0
for w, n in counts.items():
    if n < MIN_EXTRA or len(w) < 2:
        continue
    if not all(len(readings.get(ch, ())) == 1 for ch in w):
        continue
    key = "".join(next(iter(readings[ch])) for ch in w)
    if (key, w) not in entries:
        entries[(key, w)] = int(math.log2(n))
        added += 1

by_key = collections.defaultdict(list)
for (key, word), score in entries.items():
    by_key[key].append((score, word))

with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by tools/build_pinyin.py from CC-CEDICT and FrequencyWords zh_cn. CC BY-SA 4.0.\n")
    lines = 0
    for key in sorted(by_key):
        for score, word in sorted(by_key[key], key=lambda t: (-t[0], t[1])):
            f.write(f"{key}\t{word}\t{score}\n")
            lines += 1
print(f"{lines} words ({added} from the subtitles alone), {len(by_key)} spellings -> {out}")
