#!/usr/bin/env python3
"""Build app/src/main/assets/emoji.txt, the emoji panel's contents, from Unicode's
emoji-test.txt (https://unicode.org/Public/emoji/<version>/emoji-test.txt).

    python3 tools/build_emoji.py emoji-test.txt app/src/main/assets/emoji.txt

Fully-qualified emoji only, in Unicode's order, without the skin-tone variants. Each line is
    group<TAB>emoji-version<TAB>emoji
and the keyboard hides any its device cannot draw (Paint.hasGlyph), or, before Android 6,
any newer than the device's emoji.
"""
import re, sys

src, out = sys.argv[1:3]
GROUPS = {
    "Smileys & Emotion": "smileys", "People & Body": "people", "Animals & Nature": "nature",
    "Food & Drink": "food", "Travel & Places": "travel", "Activities": "activities",
    "Objects": "objects", "Symbols": "symbols", "Flags": "flags",
}
TONES = set(range(0x1F3FB, 0x1F400))
group = None
n = 0
with open(src, encoding="utf-8") as f, open(out, "w", encoding="utf-8") as o:
    o.write("# Generated by tools/build_emoji.py from Unicode emoji-test.txt (Unicode License v3).\n")
    for line in f:
        if line.startswith("# group:"):
            group = GROUPS.get(line.split(":", 1)[1].strip())
            continue
        m = re.match(r"^([0-9A-F ]+);\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)", line)
        if not m or group is None:
            continue
        cps = [int(c, 16) for c in m.group(1).split()]
        if TONES & set(cps):
            continue
        o.write(f"{group}\t{m.group(3)}\t{''.join(map(chr, cps))}\n")
        n += 1
print(f"{n} emoji -> {out}")
