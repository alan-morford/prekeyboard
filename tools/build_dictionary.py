#!/usr/bin/env python3
"""Build app/src/main/assets/dictionary.txt, the autocorrect word list.

Which words are words comes from SCOWL (en_US, size 60 and below: the size most spell
checkers ship). How common each one is comes from Hermit Dave's FrequencyWords (English,
OpenSubtitles 2018), which is CC BY-SA 4.0 - so the generated file is too; see NOTICE.

    python3 tools/build_dictionary.py <scowl-2020.12.07/final> <en_50k.txt> app/src/main/assets/dictionary.txt

Output, one word per line, most common first:  word<TAB>score
score is log2 of the word's subtitle count (7-25; a contraction counts as its stem), or 1-6 from its SCOWL size when the
subtitles never used it. Case is kept, so "I", "London" and "don't" come out as written.
"""
import math, os, re, sys

final, freq_path, out = sys.argv[1:4]

LISTS = ("english-words", "american-words", "english-contractions", "american-contractions",
         "english-upper", "american-upper", "english-proper-names", "american-proper-names")
MAX_SIZE = 60
words = {}                                    # word -> smallest SCOWL size it appears in
for name in os.listdir(final):
    base, _, size = name.rpartition(".")
    if base not in LISTS or not size.isdigit() or int(size) > MAX_SIZE:
        continue
    with open(os.path.join(final, name), encoding="latin-1") as f:
        for w in f:
            w = w.strip()
            # Letters and apostrophes only: no abbreviations with dots, no accented loanwords.
            if re.fullmatch(r"[A-Za-z][A-Za-z']*", w) and not w.endswith("'s") or w.lower() in ("let's", "it's", "that's", "he's", "she's", "what's", "where's", "who's", "there's", "here's", "how's"):
                words[w] = min(words.get(w, 99), int(size))

counts = {}
with open(freq_path, encoding="utf-8") as f:
    for line in f:
        w, n = line.split()
        counts[w] = int(n)

# Single letters are in SCOWL as words; only "a" and "I" are ones people type alone.
for w in [w for w in words if len(w) == 1 and w not in ("a", "I")]:
    del words[w]

def score(w):
    # The subtitles split contractions at the apostrophe ("don", "t"), so a contraction
    # counts as common as the word before its apostrophe: "don't" as "don", "I'm" as "I".
    key = w.split("'")[0] if "'" in w else w
    n = counts.get(key) or counts.get(key.lower())
    if n:
        return max(7, min(25, int(round(math.log2(n)))))
    return max(1, 7 - words[w] // 10)          # SCOWL 10 -> 6 ... 60 -> 1

rows = sorted(((score(w), w) for w in words), key=lambda t: (-t[0], t[1]))
with open(out, "w", encoding="utf-8") as f:
    f.write("# Generated by tools/build_dictionary.py from SCOWL and FrequencyWords. CC BY-SA 4.0.\n")
    for s, w in rows:
        f.write(f"{w}\t{s}\n")
print(f"{len(rows)} words -> {out}")
